# ---- pattern coverage on real data
from collections import Counter, defaultdict
from app.models.catalog import Problem, SheetItem
from app.patterns.mapping import observable_patterns, patterns_for
from app.patterns.taxonomy import PATTERNS, VERSION, REVIEW_STATUS
with SessionLocal() as db:
    secs = defaultdict(list)
    for pid, sec in db.execute(select(SheetItem.problem_id, SheetItem.section)):
        secs[pid].append(sec)
    cnt, tot = Counter(), Counter()
    for p in db.scalars(select(Problem)):
        k = p.platform if (p.platform != "codeforces" or p.rating) else "codeforces (unrated)"
        tot[k] += 1
        if patterns_for(p.tags, secs.get(p.id, [])):
            cnt[k] += 1
non_cat = [p for p in PATTERNS if p.kind != "category"]
obs = observable_patterns()
(D / "pattern-coverage.md").write_text(f"""# Pattern coverage (measured)

_Generated {now}. Taxonomy v{VERSION}, review status **{REVIEW_STATUS}**._

- Nodes: {len(PATTERNS)} ({len(non_cat)} patterns + {len(PATTERNS) - len(non_cat)} categories).
- Patterns that can currently accumulate evidence (some tag/section rule maps to them): **{len([p for p in non_cat if p.id in obs])} of {len(non_cat)}**. The rest are shown as `unmeasured`: {', '.join(sorted(p.id for p in non_cat if p.id not in obs))}.

| Platform | Problems mapped to >=1 pattern | Total | Share |
|---|---|---|---|
{chr(10).join(f'| {k} | {cnt[k]:,} | {tot[k]:,} | {cnt[k] / tot[k]:.1%} |' for k in tot)}

AtCoder exposes no tags in any source used, so 0% is expected and is reported as such, not guessed.
""")
